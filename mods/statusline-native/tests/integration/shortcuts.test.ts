import { expect, test } from 'claude-code/testing';
import { keys, PANE, RUN, selectSetting, setup, START, visibleText } from '../fixtures.ts';
import { t } from '../../lib/i18n/index.ts';

test('editing shortcuts preserves the native draft and changes the visible controls', { timeoutMs: 20000 }, async ($, on) => {
  const fixture = setup(on);
  await $.session.start(START);
  await $.command.run(RUN);
  const ui = await $.ui.mount(PANE);
  await keys(ui, ' ', '4');
  await selectSetting(ui, 'keyboard-shortcuts');
  await keys(ui, 'return');
  await ui.resize({ columns: 32, rows: 12 });
  await keys(ui, '/', 'save display', 'return');
  const compact = (await visibleText(ui)).replace(/ +/gu, ' ');
  expect(compact).toContain('› Save display S');
  expect(compact).toContain('OPTION ACTIVE KEY');
  expect(compact).toContain('─ Editor and draft ─');
  await ui.resize({ columns: 100, rows: 30 });
  expect((await visibleText(ui)).replace(/ +/gu, ' ')).toContain('› Save display S');
  await keys(ui, 'return');
  expect(await visibleText(ui)).toContain('Claude reserves Ctrl+D, Ctrl+X, Ctrl+Z');
  await keys(ui, { key: 'd', ctrl: true });
  expect(await visibleText(ui)).toContain('Claude reserves Ctrl+D. Choose another key.');
  await keys(ui, 'z');
  expect(fixture.store.shortcuts.bindings).toEqual({});
  const staged = (await visibleText(ui)).replace(/ +/gu, ' ');
  expect(staged).toContain('Active Terminal Ctrl+S · Client S');
  expect(staged).toContain('Pending Z');
  expect(staged).toMatch(/Tab\s*, then Enter to save/u);
  await keys(ui, 'tab');
  const focused = (await visibleText(ui)).replace(/ +/gu, ' ');
  expect(focused).toContain('›[Save shortcuts]');
  expect(focused).toContain('Tab to list');
  await keys(ui, 'return');
  expect(fixture.store.shortcuts.bindings).toEqual({ save: 'Z' });
  expect(await visibleText(ui)).not.toContain('Pending Z');
  expect(fixture.calls.filter(call => call.operation === 'apply')).toHaveLength(0);
  await keys(ui, { key: 'g', ctrl: true }, '1', 's');
  expect((await visibleText(ui)).replace(/ +/gu, ' ')).toContain('Z save');
  expect(fixture.calls.filter(call => call.operation === 'apply')).toHaveLength(0);
  await keys(ui, '/', 'Z', 'return', 'z');
  expect(fixture.calls.filter(call => call.operation === 'apply')).toHaveLength(1);
  expect(fixture.store.draft.display.instances[0]!.enabled).toBe(false);
  await ui.unmount();
});

test('finishing with pending Claude preferences shows their active apply, finish and close keys', { timeoutMs: 20000 }, async ($, on) => {
  const fixture = setup(on);
  fixture.store.shortcuts = { schema_version: 1, bindings: { 'apply-host-preferences': 'B', finish: 'J', close: 'Z' }, revision: '3'.repeat(64), warning: null };
  await $.session.start(START);
  await $.command.run(RUN);
  const ui = await $.ui.mount({ ...PANE, viewport: { columns: 170, rows: 40 }, props: { ...PANE.props, bodyColumns: 140 } });
  await keys(ui, '4', 'h');
  await selectSetting(ui, 'host-theme');
  await keys(ui, 'right', 'j');
  expect((await visibleText(ui)).replace(/ +/gu, ' ')).toContain(t('shortcuts.host-preferences-pending', 'en', { apply: 'B', finish: 'J', close: 'Z' }));
  expect(fixture.configCalls).toHaveLength(0);
  expect(fixture.closes).toHaveLength(0);
  await keys(ui, 'b');
  expect(fixture.configCalls).toEqual([{ key: 'theme', value: 'light' }]);
  await keys(ui, 'j');
  expect(fixture.closes).toHaveLength(1);
  await ui.unmount();
});

test('the native color panel shows its current apply key and Ctrl+G for cancelling edits', { timeoutMs: 20000 }, async ($, on) => {
  const fixture = setup(on);
  fixture.store.shortcuts = { schema_version: 1, bindings: { 'apply-color': 'J' }, revision: '3'.repeat(64), warning: null };
  await $.session.start(START);
  await $.command.run(RUN);
  const ui = await $.ui.mount(PANE);
  await keys(ui, { key: 'e', ctrl: true });
  await selectSetting(ui, 'item:foreground');
  await keys(ui, 'return');
  const help = t('shortcuts.color-help', 'en', { enter: 'Enter', apply: 'J', back: 'Ctrl+G' });
  const screen = async () => (await visibleText(ui)).replace(/ +/gu, ' ');
  expect(await screen()).toContain(help);
  await keys(ui, 'end', 'up', 'up', 'return');
  expect(await screen()).toContain(t('shortcuts.color-input-help', 'en', { enter: 'Enter', back: 'Ctrl+G', clear: 'Ctrl+U' }));
  await keys(ui, { key: 'g', ctrl: true }, { key: 's', ctrl: true });
  expect(await screen()).toContain(help);
  await keys(ui, 'j');
  expect((await screen()).includes(help)).toBe(false);
  expect(fixture.calls.filter(c => c.operation === 'apply')).toHaveLength(0);
  await ui.unmount();
});
