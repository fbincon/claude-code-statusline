"""Generate/check frontend protocol types from Python's canonical wire types."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import types
from typing import Literal, Union, get_args, get_origin, get_type_hints

from claude_statusline.config import catalog
from claude_statusline.ui import contracts


def type_name(value, *, aliases=True):
    if aliases:
        for name, alias in contracts.ALIASES.items():
            if value == alias:
                return name
    primitive = {
        str: "string",
        int: "number",
        bool: "boolean",
        type(None): "null",
        object: "unknown",
    }
    if value in primitive:
        return primitive[value]
    origin, args = get_origin(value), get_args(value)
    if origin is Literal:
        return " | ".join(json.dumps(arg, ensure_ascii=False) for arg in args)
    if origin in (Union, types.UnionType):
        return " | ".join(type_name(arg) for arg in args)
    if origin is list:
        inner = type_name(args[0])
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if origin is dict:
        return f"Record<{type_name(args[0])}, {type_name(args[1])}>"
    if value in contracts.WIRE_TYPES:
        return value.__name__
    raise ValueError(f"No TypeScript mapping for {value!r}")


def generated():
    rows = [
        "// Generated by tools/generate_ui_contracts.py; do not edit.",
        f"export const PROTOCOL_VERSION = {contracts.PROTOCOL_VERSION} as const;",
    ]
    for name, alias in contracts.ALIASES.items():
        rows.append(f"export type {name} = {type_name(alias, aliases=False)};")
    for scope, constant in (
        ("main", "MAIN_ITEM_IDS"),
        ("subagent", "SUBAGENT_ITEM_IDS"),
    ):
        rows.append(
            f"export const {constant} = {json.dumps(list(catalog.BY_SCOPE[scope]))} as const;"
        )
    for name in ("Palette", "DirectoryStyle", "SeparatorStyle", "ScopeLabels"):
        rows.append(
            f"export const {name.upper()}_VALUES = {json.dumps(list(get_args(contracts.ALIASES[name])))} as const;"
        )
    rows.append(
        f"export type Operation = {' | '.join(json.dumps(op) for op in contracts.OPERATIONS)};"
    )
    for wire in contracts.WIRE_TYPES:
        rows.append(f"export interface {wire.__name__} {{")
        rows.extend(
            f"  {key}: {type_name(value)};"
            for key, value in get_type_hints(wire).items()
        )
        rows.append("}")
    rows.extend(
        [
            "export interface ResultMap { "
            + " ".join(
                f"{op}: {wire.__name__};" for op, wire in contracts.RESULTS.items()
            )
            + " }",
            "export type ResultFor<O extends Operation> = ResultMap[O];",
            "export interface Request { protocol_version: typeof PROTOCOL_VERSION; operation: Operation; payload: unknown; }",
            "export type Result = "
            + " | ".join(
                wire.__name__
                for wire in contracts.WIRE_TYPES
                if wire.__name__.endswith("Result")
            )
            + ";",
            "export type Response = { protocol_version: typeof PROTOCOL_VERSION; result: Result } | { protocol_version: typeof PROTOCOL_VERSION; error: ProtocolError };",
        ]
    )
    return "\n".join(rows) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("mods/statusline-native/lib/generated-contracts.ts"),
    )
    args = parser.parse_args()
    content = generated()
    if args.check:
        if (
            not args.output.is_file()
            or args.output.read_text(encoding="utf-8") != content
        ):
            parser.exit(
                1,
                "Generated UI contracts are stale; run tools/generate_ui_contracts.py\n",
            )
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
