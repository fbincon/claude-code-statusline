import test, { type TestContext } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { commandFor } from '@fbincon/statusline-platform/commands';
import { repoRoot } from '../common.js';
import { modLibraries } from '../mod-support.js';
async function fixture(t: TestContext) {
    const root = mkdtempSync(join(tmpdir(), 'ts03-mod 中文 '));
    t.after(() => rmSync(root, { recursive: true, force: true }));
    const config = join(root, 'config'), bin = join(root, 'empty-bin');
    mkdirSync(config);
    mkdirSync(bin);
    const entry = join(repoRoot, 'packages/cli/dist/src/entry.js'), launch = { executable: process.execPath, args: [entry] };
    writeFileSync(join(config, 'settings.json'), JSON.stringify({ statusLine: { type: 'command', command: commandFor(launch, 'render') }, subagentStatusLine: { type: 'command', command: commandFor(launch, 'render-subagents') }, permissions: { allow: ['Read'] } }));
    const run = (command: string, input: string) => {
        const result = spawnSync(process.execPath, [entry, command], { encoding: 'utf8', timeout: 20000, input,
            env: { ...process.env, PATH: bin, HOME: root, USERPROFILE: root, CLAUDE_CONFIG_DIR: config, CLAUDE_STATUSLINE_RUNTIME_DIR: join(root, 'runtime'), CLAUDE_STATUSLINE_SESSIONS_DIR: join(root, 'sessions') } });
        assert.ifError(result.error);
        assert.equal(result.stderr, '');
        return { exitCode: result.status!, stdout: result.stdout, stderr: result.stderr };
    };
    return { root, config, run, ...await modLibraries(root) };
}
test('unmodified native Mod request/parser accepts every TS UI v11 operation with Python absent from PATH', async (t) => {
    const f = await fixture(t), backend = f.native, operations = new Set<string>();
    const call = (operation: string, payload = {}) => { operations.add(operation); return backend.parseResponse(operation, f.run('ui', backend.requestText(operation, payload))); };
    const description = call('describe');
    assert.equal(description.backend_version, '2.0.0');
    assert.equal(description.catalog.length, 78);
    const baseline = call('read');
    assert.equal(baseline.installed, true);
    assert.equal(baseline.installation.statusLine.state, 'owned');
    assert.equal(call('read_ui_preferences').ui_language, 'en');
    assert.equal(call('set_ui_language', { ui_language: 'zh-CN' }).ui_language, 'zh-CN');
    const changed = call('preset', { draft: baseline.draft, preset: 'left-right' }).draft;
    changed.display.statusline_language = 'ja';
    const file = join(f.root, 'portable 日本語.json');
    assert.equal(call('export', { draft: changed, path: file, overwrite: false }).path, file);
    assert.deepEqual(call('import', { draft: baseline.draft, path: file }).draft, changed);
    const review = call('review_import', { draft: baseline.draft, path: file });
    assert.deepEqual(review.draft, changed);
    assert.ok(review.changes.length > 0);
    for (const width of [40, 80, 120]) {
        const result = call('preview', { draft: changed, width });
        assert.equal(result.sample, true);
        assert.ok(result.main.length);
    }
    const saved = call('apply', { draft: changed, expected_revision: baseline.revision });
    assert.equal(saved.changed, true);
    assert.deepEqual(saved.draft, changed);
    assert.ok(saved.backup_dir);
    const bytes = readFileSync(join(f.config, 'claude-statusline.json')), backups = readdirSync(join(f.config, 'backups/statusline'));
    const repeated = call('apply', { draft: saved.draft, expected_revision: saved.revision });
    assert.equal(repeated.changed, false);
    assert.equal(repeated.backup_dir, null);
    assert.deepEqual(readdirSync(join(f.config, 'backups/statusline')), backups);
    assert.throws(() => call('apply', { draft: baseline.draft, expected_revision: baseline.revision }), (error: any) => error instanceof backend.BackendError && error.code === 'configuration_conflict');
    assert.deepEqual(readFileSync(join(f.config, 'claude-statusline.json')), bytes);
    assert.throws(() => call('preview', { draft: changed, width: 1 }), (error: any) => error.code === 'invalid_request');
    const response = f.run('ui', '{"protocol_version":1,"operation":"read","payload":{}}');
    assert.equal(response.exitCode, 2);
    assert.throws(() => backend.parseResponse('read', response), (error: any) => error.code === 'unsupported_protocol');
    assert.throws(() => backend.parseResponse('read', { ...f.run('ui', backend.requestText('read')), isStdoutTruncated: true }), (error: any) => error.code === 'backend_output_truncated');
    assert.deepEqual([...operations].sort(), description.operations.toSorted());
    const rendered = f.run('render', '{"model":{"id":"Python-free"},"context_window":{"remaining_percentage":50}}');
    assert.equal(rendered.exitCode, 0);
    assert.ok(rendered.stdout.includes('Python-free'));
    assert.equal(f.run('hook', '{"hook_event_name":"UserPromptSubmit","session_id":"isolated","prompt_id":"p"}').exitCode, 0);
    const agents = f.run('render-subagents', '{"tasks":[{"id":"a","name":"Agent","status":"running"}]}');
    assert.equal(agents.exitCode, 0);
    assert.equal(JSON.parse(agents.stdout).id, 'a');
    const slash = f.run('slash-hook', '{"hook_event_name":"UserPromptExpansion","expansion_type":"slash_command","command_name":"statusline-config","command_args":"help"}');
    assert.equal(slash.exitCode, 0);
    assert.equal(JSON.parse(slash.stdout).decision, 'block');
});
test('unmodified runtime Mod queue confirms TS acknowledgements, retries and v1 compatibility without Python', async (t) => {
    const f = await fixture(t), { Queue, confirmedResponse } = f.runtime, queue = new Queue(true, true), now = Date.now();
    const preferences = (timing: boolean, metrics: boolean) => writeFileSync(join(f.config, 'claude-statusline-runtime.json'), JSON.stringify({ schema_version: 2, native_timing: timing, live_metrics: metrics }));
    const observe = (rows: unknown[], version = 2) => f.run('runtime', JSON.stringify({ protocol_version: version, operation: 'observe', payload: { observations: rows } }));
    const read = (version = 2) => f.run('runtime', JSON.stringify({ protocol_version: version, operation: 'read', payload: { session_id: 'session', prompt_id: 'p' } }));
    preferences(true, true);
    queue.bind('session', now);
    queue.push('heartbeat', { host_version: '2.1.296', loaded_at_ms: now }, now);
    queue.push('prompt', {}, now + 1, { prompt_id: 'p' });
    queue.push('permission', { mode: 'plan', live: false }, now + 2, { prompt_id: 'p' });
    const batch = queue.batch(), first = observe(batch);
    assert.equal(first.exitCode, 0);
    assert.equal(confirmedResponse(first.stdout, '2.0.0', batch.length), true);
    assert.equal(JSON.parse(first.stdout).result.accepted, 3);
    assert.equal(confirmedResponse(first.stdout, '0.0.0', batch.length), false);
    assert.equal(confirmedResponse(first.stdout, '2.0.0', 99), false);
    const duplicate = observe(batch);
    assert.equal(confirmedResponse(duplicate.stdout, '2.0.0', batch.length), true);
    assert.equal(JSON.parse(duplicate.stdout).result.ignored, 3);
    queue.acknowledge(batch);
    assert.equal(queue.pending.length, 0);
    for (const version of [1, 2]) {
        const result = read(version);
        assert.equal(result.exitCode, 0);
        const response = JSON.parse(result.stdout);
        assert.equal(response.protocol_version, version);
        assert.equal(response.result.state.current_prompt_id, 'p');
        assert.equal(response.result.metrics['permission-mode'].value, 'plan');
    }
    queue.push('heartbeat', { host_version: '2.1.296', loaded_at_ms: now }, now + 3);
    const legacy = observe(queue.batch(), 1);
    assert.equal(legacy.exitCode, 0);
    assert.equal(JSON.parse(legacy.stdout).protocol_version, 1);
    assert.equal(confirmedResponse(legacy.stdout, '2.0.0', 1), false);
    queue.acknowledge(queue.batch());
    queue.push('heartbeat', { host_version: '2.1.296', loaded_at_ms: now }, now + 4);
    const invalid = observe([{ ...queue.batch()[0], unexpected: true }]);
    assert.equal(invalid.exitCode, 2);
    assert.equal(confirmedResponse(invalid.stdout, '2.0.0', 1), false);
    assert.equal(queue.pending.length, 1);
    preferences(false, false);
    const disabled = observe(queue.batch());
    assert.equal(confirmedResponse(disabled.stdout, '2.0.0', 1), true);
    assert.deepEqual({ ...JSON.parse(disabled.stdout).result }, { backend_version: '2.0.0', enabled: false, native_timing: false, live_metrics: false, accepted: 0, ignored: 1 });
    preferences(true, false);
    const timing = new Queue(true, false);
    timing.bind('timing-only', now);
    timing.push('heartbeat', { host_version: '2.1.296', loaded_at_ms: now }, now);
    timing.push('permission', { mode: 'plan', live: false }, now + 1);
    assert.equal(timing.pending.length, 1);
    assert.equal(confirmedResponse(observe(timing.batch()).stdout, '2.0.0', 1), true);
    const bounded = new Queue();
    bounded.bind('bounded', now);
    bounded.push('heartbeat', { host_version: '2.1.296', loaded_at_ms: now }, now);
    for (let i = 0; i < 1030; i++)
        bounded.push('prompt', {}, now + i + 1, { prompt_id: 'p' + i });
    assert.equal(bounded.pending.length, 1024);
    assert.equal(bounded.dropped, true);
    assert.equal(bounded.batch().length, 256);
    assert.equal(bounded.pending[0].kind, 'heartbeat');
});
