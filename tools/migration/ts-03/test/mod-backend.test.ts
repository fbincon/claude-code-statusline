async function fixture(t: TestContext) {
    const root = mkdtempSync(join(tmpdir(), 'ts03-mod 中文 '));
    t.after(() => rmSync(root, { recursive: true, force: true }));
    const config = join(root, 'config'), bin = join(root, 'empty-bin');
    mkdirSync(config);
    mkdirSync(bin);
    const entry = join(repoRoot, 'packages/cli/dist/src/entry.js'), launch = { executable: process.execPath, args: [entry] };
    writeFileSync(join(config, 'settings.json'), JSON.stringify({ statusLine: { type: 'command', command: commandFor(launch, 'render') }, subagentStatusLine: { type: 'command', command: commandFor(launch, 'render-subagents') }, permissions: { allow: ['Read'] } }));
    const run = (command: string, input: string) => {
        const result = spawnSync(process.execPath, [entry, command], { encoding: 'utf8', timeout: 20000, input,
            env: { ...process.env, PATH: bin, HOME: root, USERPROFILE: root, CLAUDE_CONFIG_DIR: config, CLAUDE_STATUSLINE_RUNTIME_DIR: join(root, 'runtime'), CLAUDE_STATUSLINE_SESSIONS_DIR: join(root, 'sessions') } });
        assert.ifError(result.error);
        assert.equal(result.stderr, '');
        return { exitCode: result.status!, stdout: result.stdout, stderr: result.stderr };
    };
    return { root, config, run, ...await modLibraries(root) };
}
