export const ROOT = fileURLToPath(new URL('../../../../', import.meta.url));
const header = '// Generated by tools/generation/resources.ts; do not edit.\n';
const utf8 = (path: string) => fs.readFileSync(path, 'utf8').replaceAll('\r\n', '\n');
const sha = (text: string) => createHash('sha256').update(text, 'utf8').digest('hex');
const json = (value: unknown, indent?: number, ensureAscii = true, sortKeys = false) => pythonJson(value, { indent, ensureAscii, sortKeys });

export interface LanguageSource { code: string; name: string }
export function languages(directory: string, complete = true) {
  const registry = decode(utf8(join(directory, 'languages.json'))) as LanguageSource[];
  if (!Array.isArray(registry) || !registry.length || registry[0]?.code !== 'en') throw new Error('English must be the first fallback language');
  const codes = new Set<string>(), modules = new Set<string>();
  for (const entry of registry) {
    if (!entry || Object.keys(entry).sort().join(',') !== 'code,name' || typeof entry.code !== 'string' || !/^[a-z]{2,3}(?:-[A-Z][a-z]{3})?(?:-(?:[A-Z]{2}|[0-9]{3}))?$/u.test(entry.code)) throw new Error('Invalid language registry entry');
    const module = entry.code.replaceAll('-', '_').toLowerCase();
    if (codes.has(entry.code) || modules.has(module) || typeof entry.name !== 'string' || !entry.name.trim() || /[\p{Cc}\p{Cs}]/u.test(entry.name)) throw new Error('Duplicate or unsafe language registry entry');
    codes.add(entry.code); modules.add(module);
  }
  const discovered = fs.readdirSync(join(directory, 'locales')).filter(name => name.endsWith('.json')).map(name => name.slice(0, -5));
  if (discovered.length !== codes.size || discovered.some(code => !codes.has(code))) throw new Error('Registry/resource mismatch');
  const data = Object.fromEntries(registry.map(entry => [entry.code, decode(utf8(join(directory, 'locales', entry.code + '.json'))) as Record<string, string>]));
  const english = data.en!;
  if (!english || Array.isArray(english) || typeof english !== 'object' || !Object.keys(english).length) throw new Error('Invalid English messages');
  function placeholders(text: string): string[] {
    const names = new Set<string>();
    for (let i = 0; i < text.length; i++) {
      if ((text[i] === '{' || text[i] === '}') && text[i + 1] === text[i]) { i++; continue; }
      if (text[i] === '}') throw new Error('Unmatched translation brace');
      if (text[i] !== '{') continue;
      const end = text.indexOf('}', i + 1), name = text.slice(i + 1, end);
      if (end < 0 || !/^[A-Za-z_][A-Za-z_0-9]*$/u.test(name)) throw new Error('Only named, unformatted placeholders are supported');
      names.add(name); i = end;
    }
    return [...names].sort();
  }
  for (const [language, entries] of Object.entries(data)) {
    if (!entries || typeof entries !== 'object' || Array.isArray(entries) || (complete && Object.keys(entries).length !== Object.keys(english).length) || Object.keys(entries).some(key => !Object.hasOwn(english, key))) throw new Error(`Translation keys differ: ${language}`);
    for (const [key, value] of Object.entries(entries)) {
      if (typeof value !== 'string' || /\p{Cs}/u.test(value) || /\p{Cc}/u.test(value.replaceAll('\n', '').replaceAll('\t', '')) || (!value.trim() && english[key]!.trim())) throw new Error(`Invalid translation: ${language}:${key}`);
      if (JSON.stringify(placeholders(value)) !== JSON.stringify(placeholders(english[key]!))) throw new Error(`Placeholder mismatch: ${language}:${key}`);
      if (key.startsWith('statusline.') && /[\p{Cc}\p{Cs}\p{Zl}\p{Zp}]/u.test(value)) throw new Error(`Unsafe statusline message: ${language}:${key}`);
      if (/^statusline\.(prefix|short|values|live\.label)\./u.test(key) && placeholders(value).length) throw new Error('Statusline labels cannot contain placeholders');
    }
  }
  return { registry, data };
}

export function languageCoverage(directory: string) {
  const { data } = languages(directory, false), keys = Object.keys(data.en!);
  return Object.fromEntries(Object.entries(data).map(([code, entries]) => [code, {
    messages: Object.keys(entries).length, total: keys.length,
    percent: Number(fixed(100 * Object.keys(entries).length / keys.length, 2)),
    missing: keys.filter(key => !Object.hasOwn(entries, key)).sort(),
    statusline_messages: Object.keys(entries).filter(key => key.startsWith('statusline.')).length,
  }]));
}

export function languageOutputs(root = ROOT): Map<string, string> {
  const directory = join(root, 'packages/core/resources/i18n');
  const { registry, data } = languages(directory);
  const names = Object.fromEntries(registry.map(entry => [entry.code, entry.name]));
  const outputs = new Map<string, string>();
  const registryText = header + 'export const LANGUAGES = ' + json(registry.map(entry => entry.code)) + ' as const;\nexport type Language = typeof LANGUAGES[number];\nexport const LANGUAGE_NAMES: Record<Language, string> = ' + json(names, undefined, false) + ';\n';
  const all = registryText + 'export const LOCALES = ' + json(data, 2, false) + ' as const;\nexport type MessageKey = keyof typeof LOCALES.en;\n';
  outputs.set('packages/core/src/i18n/registry.ts', registryText);
  outputs.set('packages/core/src/i18n/generated-locales.ts', all);
  outputs.set('mods/statusline-native/lib/i18n/generated-locales.ts', all);
  outputs.set('src/claude_statusline/i18n/languages.json', utf8(join(directory, 'languages.json')));
  const pythonHeader = '# Generated by tools/generation/resources.ts; do not edit.\n';
  const modules = Object.fromEntries(registry.map(entry => [entry.code, entry.code.replaceAll('-', '_').toLowerCase()]));
  outputs.set('src/claude_statusline/i18n/_generated_languages.py', pythonHeader + 'LANGUAGES = tuple(' + json(registry.map(entry => entry.code)) + ')\n' +
    'LANGUAGE_NAMES = ' + json(names, 2, false) + '\nSTATUSLINE_MODULES = ' + json(modules, 2, false) + '\n');
  outputs.set('src/claude_statusline/i18n/_generated_statusline/__init__.py', pythonHeader + '"""Language modules are imported individually on demand."""\n');
  for (const { code } of registry) {
    outputs.set('src/claude_statusline/i18n/locales/' + code + '.json', utf8(join(directory, 'locales', code + '.json')));
    const messages = Object.fromEntries(Object.entries(data[code]!).filter(([key]) => key.startsWith('statusline.')));
    outputs.set('packages/core/src/i18n/statusline/' + code + '.ts', header + 'export const MESSAGES = ' + json(messages, 2, false) + ' as const;\n');
    outputs.set('src/claude_statusline/i18n/_generated_statusline/' + modules[code] + '.py', pythonHeader + 'MESSAGES = ' + json(messages, 2, false, true) + '\n');
  }
  return outputs;
}

export function unicodeOutputs(root = ROOT): Map<string, string> {
  const directory = join(root, 'tools/unicode'), raw = utf8(join(directory, 'data.json'));
  const source = JSON.parse(raw) as { unicode_version: string; reference: string; tables: Record<string, number[][]>; source_sha256: Record<string, string> };
  if (source.unicode_version !== '18.0.0' || source.reference !== 'wcwidth 0.9.1') throw new Error('Unicode reference changed');
  const tables = source.tables;
  const width = Object.fromEntries(['ZERO_WIDTH', 'WIDE_EASTASIAN', 'VS16_NARROW_TO_WIDE', 'VS15_WIDE_TO_NARROW', 'CATEGORY_MC', 'EXTENDED_PICTOGRAPHIC'].map(key => [key, tables[key]!]));
  const order = (a: number[], b: number[]) => a[0]! - b[0]! || a[1]! - b[1]!;
  width.VIRAMA = [...tables.ISC_VIRAMA!, ...tables.ISC_INVISIBLE_STACKER!].sort(order);
  const grapheme = Object.fromEntries(['EXTENDED_PICTOGRAPHIC', 'INCB_LINKER', 'INCB_CONSONANT', 'INCB_EXTEND'].map(key => [key, tables[key]!]));
  const properties = ['CR', 'LF', 'CONTROL', 'EXTEND', 'ZWJ', 'REGIONAL_INDICATOR', 'PREPEND', 'SPACINGMARK', 'L', 'V', 'T', 'LV', 'LVT'];
  grapheme.BREAK_PROPERTIES = properties.flatMap((name, index) => ['LV', 'LVT'].includes(name) ? [] : tables['GRAPHEME_' + name]!.map(([lo, hi]) => [lo!, hi!, index + 1])).sort(order);
  const license = utf8(join(directory, 'WCWIDTH-LICENSE.txt')) + '\n' + utf8(join(directory, 'UNICODE-LICENSE.txt'));
  const description = `Generated by tools/generation/resources.ts; Unicode 18.0.0; wcwidth 0.9.1; data SHA256 ${sha(raw)}.`;
  const entries = Object.entries({ ...width, ...grapheme });
  const ts = '/* ' + description + '\n' + license.replaceAll('*/', '* /') + '*/\n' + entries.map(([name, rows]) => {
    const type = 'readonly (readonly [' + Array(rows[0]!.length).fill('number').join(', ') + '])[]';
    return 'let cached_' + name + ': ' + type + ' | undefined;\nexport function ' + name + '(): ' + type + ' { return cached_' + name + ' ??= JSON.parse(' + JSON.stringify(JSON.stringify(rows)) + '); }';
  }).join('\n') + '\nexport function initializedTables(): number { return [' + entries.map(([name]) => 'cached_' + name).join(', ') + '].filter(Boolean).length; }\n';
  const outputs = new Map<string, string>([['packages/core/src/unicode/generated-unicode.ts', ts], ['mods/statusline-native/lib/generated-unicode.ts', ts]]);
  for (const [name, values] of [['_unicode_width.py', width], ['_unicode_grapheme.py', grapheme]] as const) {
    const lines = Object.entries(values).map(([key, rows]) => {
      const format = '<' + 'I'.repeat(rows[0]!.length);
      const bytes = Buffer.alloc(rows.length * rows[0]!.length * 4);
      rows.flat().forEach((value, index) => bytes.writeUInt32LE(value, index * 4));
      const packed = bytes.toString('hex');
      const chunks = packed.match(/.{1,64}/g) ?? [];
      return key + " = tuple(_iter_unpack('" + format + "', bytes.fromhex(\n" + chunks.map(chunk => '    "' + chunk + '"\n').join('') + ')))\n';
    });
    outputs.set('src/claude_statusline/rendering/' + name, '"""' + description + '\n\n' + license.replaceAll('"""', '') + '"""\n\n# Fixed little-endian integers avoid compiling thousands of tuple literals.\nfrom struct import iter_unpack as _iter_unpack\n\n' + lines.join('\n'));
  }
  const conformance = utf8(join(directory, 'GraphemeBreakTest.txt'));
  const cases: string[][] = [];
  for (const line of conformance.split('\n')) {
    const tokens = line.split('#')[0]!.trim().split(/\s+/u).filter(Boolean);
    if (!tokens.length) continue;
    const groups: string[] = []; let group = '';
    for (const token of tokens) {
      if (token === '÷') { if (group) { groups.push(group); group = ''; } }
      else if (token !== '×') group += String.fromCodePoint(parseInt(token, 16));
    }
    cases.push(groups);
  }
  const fixtures = JSON.parse(utf8(join(root, 'tests/fixtures/graphemes.json')));
  outputs.set('mods/statusline-native/tests/generated-unicode-fixtures.ts', header + 'export const GRAPHEME_CASES = ' + json(fixtures.cases) + ';\nexport const BREAK_CASES = ' + json(cases) + ';\n');
  outputs.set('tools/unicode/provenance.json', json({ unicode_version: '18.0.0', reference: 'wcwidth 0.9.1', data_sha256: sha(raw), source_sha256: source.source_sha256,
    conformance_url: 'https://www.unicode.org/Public/18.0.0/ucd/auxiliary/GraphemeBreakTest.txt', conformance_sha256: sha(conformance), conformance_cases: cases.length,
    licenses: ['WCWIDTH-LICENSE.txt', 'UNICODE-LICENSE.txt'] }, 2) + '\n');
  return outputs;
}

export function outputs(root = ROOT): Map<string, string> {
  const result = new Map([...languageOutputs(root), ...unicodeOutputs(root)]);
  for (const [source, destination] of editorSources(root)) {
    let body = utf8(join(root, source));
    const backend = source.endsWith('/backend.ts'), text = source.endsWith('/text.ts');
    body = body.replaceAll('../contracts/ui.js', backend ? './generated-contracts.ts' : '../generated-contracts.ts')
      .replaceAll('../i18n/messages.js', backend ? './i18n/index.ts' : '../i18n/index.ts')
      .replaceAll('../unicode/index.js', '../lib/unicode.ts');
    if (backend) body = body.replaceAll('./appearance.js', './editor/appearance.ts');
    if (!backend && !text) body = body.replaceAll('./backend.js', '../backend.ts').replaceAll('./text.js', '../../ui/text.ts');
    body = body.replace(/(from ['"][^'"]+)\.js(['"])/gu, '$1.ts$2');
    result.set(destination, header + body);
  }
  for (const name of ['statusline-native', 'statusline-runtime']) {
    result.set(`mods/${name}/lib/launch.ts`, header + utf8(join(root, 'packages/core/src/integration/binding.ts')));
  }
  const codes = languages(join(root, 'packages/core/resources/i18n')).registry.map(entry => entry.code);
  const mainIds = catalogData.filter(item => item.scope === 'main').map(item => item.id);
  const subagentIds = catalogData.filter(item => item.scope === 'subagent').map(item => item.id);
  const presets = Object.entries(ROWS).map(([id, rows]) => ({ id, label: id.replaceAll('-', ' ').replace(/\b\w/gu, letter => letter.toUpperCase()), rows, layout_mode: id === 'minimal' ? 'auto' : 'explicit' }));
  const generatedCatalog = { MAIN_ITEM_IDS: mainIds, SUBAGENT_ITEM_IDS: subagentIds, PRESETS: presets };
  result.set('packages/core/src/contracts/generated-catalog.ts', header + Object.entries(generatedCatalog).map(([name, value]) => 'export const ' + name + ' = ' + json(value) + ' as const;\n').join(''));
  for (const [source, destination] of [['ui', 'mods/statusline-native/lib/generated-contracts.ts'], ['runtime', 'mods/statusline-runtime/lib/generated-contracts.ts']]) {
    let body = utf8(join(root, 'packages/core/src/contracts/' + source + '.ts')).split('\n').slice(1).filter(line => !line.startsWith('import ') || !['"../i18n/registry.js";', '"./generated-catalog.js";'].some(suffix => line.endsWith(suffix))).join('\n');
    if (/^import /mu.test(body)) throw new Error('A Mod contract acquired an unsupported module dependency');
    if (source === 'ui') {
      body = body.replaceAll('LANGUAGES', json(codes))
        .replace('export type StatuslineLanguage = Language;', 'export type StatuslineLanguage = ' + codes.map(code => json(code)).join(' | ') + ';')
        .replace('export type MainItemId = typeof MAIN_ITEM_IDS[number];', 'export type MainItemId = ' + mainIds.map(id => json(id)).join(' | ') + ';')
        .replace('export type SubagentItemId = typeof SUBAGENT_ITEM_IDS[number];', 'export type SubagentItemId = ' + subagentIds.map(id => json(id)).join(' | ') + ';')
        .replace(/^(export const STATUSLINELANGUAGE_VALUES = .+);$/mu, '$1 as const;');
      for (const [name, value] of Object.entries(generatedCatalog)) body = body.replace('export const ' + name + ' = generated' + name + ';', 'export const ' + name + ' = ' + json(value) + ' as const;');
    }
    result.set(destination!, header + body);
  }
  result.set('packages/core/src/config/generated-constants.ts', header + 'import type { Scope, VisibilityRule } from "../contracts/ui.js";\n' +
    'export const ITEM_DEFAULTS = ' + json(ITEM_DEFAULTS) + ' as const;\n' +
    'export const FORMAT_CHOICES = ' + json(FORMAT_CHOICES) + ' as const;\n' +
    'export const FORMAT_DEFAULTS = ' + json(FORMAT_DEFAULTS) + ' as const;\n' +
    'export const VISIBILITY_ITEMS: Record<Scope, Record<string, VisibilityRule>> = ' + json(VISIBILITY_ITEMS) + ';\n');
  const search = JSON.parse(utf8(join(root, 'tests/fixtures/editor-search.json')));
  result.set('mods/statusline-native/tests/generated-search-fixtures.ts', header + 'export const APPEARANCE_CASES = ' + utf8(join(root, 'tests/fixtures/appearance.json')).trim() + ';\n' +
    'export const SEARCH_CASES = ' + json(search, 2, false) + ';\nexport const SEARCH_CATALOG = ' + json(catalogData, 2, false) + ';\n');
  for (const [source, destination] of [['unicode/index.ts', 'mods/statusline-native/lib/unicode.ts'], ['i18n/messages.ts', 'mods/statusline-native/lib/i18n/index.ts']]) {
    result.set(destination!, header + utf8(join(root, 'packages/core/src/' + source)).replaceAll("./generated-unicode.js", "./generated-unicode.ts").replaceAll("./generated-locales.js", "./generated-locales.ts"));
  }
  return result;
}

/** Keep the Mods self-contained; the core is the sole editable source of these modules. */
export function editorSources(root = ROOT): [string, string][] {
  return fs.readdirSync(join(root, 'packages/core/src/editor')).filter(name => name.endsWith('.ts')).sort().map(name => [
    'packages/core/src/editor/' + name,
    name === 'backend.ts' ? 'mods/statusline-native/lib/backend.ts' : name === 'text.ts' ? 'mods/statusline-native/ui/text.ts' : 'mods/statusline-native/lib/editor/' + name,
  ]);
}

export function obsoleteOutputs(values: ReadonlyMap<string, string>, root = ROOT): string[] {
  const obsolete: string[] = [];
  for (const [directory, extension] of [['packages/core/src/i18n/statusline', '.ts'], ['src/claude_statusline/i18n/_generated_statusline', '.py']]) {
    const folder = join(root, directory!);
    if (!fs.existsSync(folder)) continue;
    for (const entry of fs.readdirSync(folder)) {
      const name = directory + '/' + entry;
      if (!entry.endsWith(extension!) || values.has(name)) continue;
      if (!/^[#/].*Generated by tools\/(?:generation\/resources\.ts|generate_i18n\.py)/u.test(utf8(join(root, name)))) throw new Error('Unowned file in generated language directory: ' + name);
      obsolete.push(name);
    }
  }
  const registry = join(root, 'src/claude_statusline/i18n/languages.json');
  const oldCodes = fs.existsSync(registry) ? new Set((JSON.parse(utf8(registry)) as LanguageSource[]).map(entry => entry.code)) : new Set<string>();
  const directory = 'src/claude_statusline/i18n/locales';
  if (fs.existsSync(join(root, directory))) for (const entry of fs.readdirSync(join(root, directory))) {
    const name = directory + '/' + entry;
    if (!entry.endsWith('.json') || values.has(name)) continue;
    if (!oldCodes.has(entry.slice(0, -5))) throw new Error('Unowned compatibility language pack: ' + entry);
    obsolete.push(name);
  }
  return obsolete;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const check = process.argv.includes('--check');
  if (process.argv.includes('--coverage') && process.argv.length === 3) {
    const coverage = languageCoverage(join(ROOT, 'packages/core/resources/i18n'));
    console.log(JSON.stringify(coverage, null, 2));
    process.exit(Object.values(coverage).some(row => row.missing.length) ? 1 : 0);
  }
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: resources [--check | --coverage]');
  const values = outputs();
  const obsolete = obsoleteOutputs(values);
  if (check && obsolete.length) throw new Error('Obsolete generated resources: ' + obsolete.join(', '));
  for (const [name, value] of values) {
    const path = join(ROOT, name);
    if (check) { if (!fs.existsSync(path) || utf8(path) !== value) throw new Error('Stale generated resource: ' + name); }
    else { fs.mkdirSync(resolve(path, '..'), { recursive: true }); fs.writeFileSync(path, value, 'utf8'); }
  }
  if (!check) for (const name of obsolete) fs.unlinkSync(join(ROOT, name));
  console.log(JSON.stringify({ generated_resources: values.size, check }));
}
