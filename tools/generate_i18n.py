"""Validate canonical language resources and generate the native translation data."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import pprint
from string import Formatter

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ROOT / "src/claude_statusline/i18n/locales"
OUTPUT = ROOT / "mods/statusline-native/lib/i18n/generated-locales.ts"
STATUSLINE_OUTPUT = ROOT / "src/claude_statusline/i18n/_generated_statusline.py"


def unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate translation key: {key}")
        result[key] = value
    return result


def placeholders(value):
    result = set()
    for _, field, spec, conversion in Formatter().parse(value):
        if field is not None:
            if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", field) or spec or conversion:
                raise ValueError(f"Only named, unformatted placeholders are supported: {value}")
            result.add(field)
    return result


def resources():
    data = {p.stem: json.loads(p.read_text(encoding="utf-8"), object_pairs_hook=unique) for p in sorted(LOCALES.glob("*.json"))}
    if set(data) != {"en", "zh-CN"}:
        raise ValueError("Expected en and zh-CN resources")
    for language, entries in data.items():
        if not isinstance(entries, dict) or set(entries) != set(data["en"]):
            raise ValueError(f"Translation keys differ: {language}")
        for key, value in entries.items():
            if not isinstance(value, str) or re.search(r"[\x00-\x08\x0b-\x1f\x7f]", value):
                raise ValueError(f"Invalid translation: {language}:{key}")
            if placeholders(value) != placeholders(data["en"][key]):
                raise ValueError(f"Placeholder mismatch: {language}:{key}")
    return data


def generated():
    data = resources()
    return "// Generated by tools/generate_i18n.py; do not edit.\n" + "export const LOCALES = " + json.dumps(data, ensure_ascii=False, indent=2) + " as const;\nexport type MessageKey = keyof typeof LOCALES.en;\n"


def generated_statusline():
    data = {
        language: {key: value for key, value in entries.items() if key.startswith("statusline.")}
        for language, entries in resources().items()
    }
    return '# Generated by tools/generate_i18n.py; do not edit.\nLOCALES = ' + pprint.pformat(data, width=100, sort_dicts=True) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for output, content in ((OUTPUT, generated()), (STATUSLINE_OUTPUT, generated_statusline())):
        if args.check:
            if not output.is_file() or output.read_text(encoding="utf-8") != content:
                parser.exit(1, "Generated locales are stale; run tools/generate_i18n.py\n")
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
