"""Validate registered languages and deterministically generate runtime resources."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
from string import Formatter
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src/claude_statusline/i18n"
LOCALES = PACKAGE / "locales"
LANGUAGES_FILE = PACKAGE / "languages.json"
REGISTRY_OUTPUT = PACKAGE / "_generated_languages.py"
OUTPUT = ROOT / "mods/statusline-native/lib/i18n/generated-locales.ts"
STATUSLINE_OUTPUT = PACKAGE / "_generated_statusline"
HEADER = "# Generated by tools/generation/resources.ts; do not edit.\n"


def unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate translation key: {key}")
        result[key] = value
    return result


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique)


def registry():
    entries = read_json(LANGUAGES_FILE)
    result = {}
    modules = set()
    if not isinstance(entries, list) or not entries:
        raise ValueError("Language registry must be a nonempty array")
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != {"code", "name"}:
            raise ValueError("Language entries require code and name")
        code, name = entry["code"], entry["name"]
        if not isinstance(code, str) or not re.fullmatch(r"[a-z]{2,3}(?:-[A-Z][a-z]{3})?(?:-(?:[A-Z]{2}|[0-9]{3}))?", code):
            raise ValueError(f"Invalid language code: {code!r}")
        module = code.replace("-", "_").lower()
        if code in result or module in modules:
            raise ValueError(f"Duplicate language: {code}")
        if not isinstance(name, str) or not name.strip() or any(unicodedata.category(c) in ("Cc", "Cs") for c in name):
            raise ValueError(f"Invalid language name: {code}")
        result[code] = name
        modules.add(module)
    if next(iter(result)) != "en":
        raise ValueError("English must be the first registered fallback language")
    return result


def placeholders(value):
    result = set()
    for _, field, spec, conversion in Formatter().parse(value):
        if field is not None:
            if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", field) or spec or conversion:
                raise ValueError(f"Only named, unformatted placeholders are supported: {value}")
            result.add(field)
    return result


def resources(*, complete=True):
    names = registry()
    discovered = {path.stem: path for path in LOCALES.glob("*.json")}
    if set(discovered) != set(names):
        raise ValueError(f"Registry/resource mismatch: missing={sorted(set(names) - set(discovered))}, unregistered={sorted(set(discovered) - set(names))}")
    data = {code: read_json(discovered[code]) for code in names}
    english = data["en"]
    if not isinstance(english, dict) or not english:
        raise ValueError("English messages must be a nonempty object")
    for language, entries in data.items():
        if not isinstance(entries, dict) or set(entries) - set(english) or (complete and set(entries) != set(english)):
            raise ValueError(f"Translation keys differ: {language}")
        for key, value in entries.items():
            if not isinstance(value, str) or any(
                unicodedata.category(c) == "Cs"
                or (unicodedata.category(c) == "Cc" and c not in "\n\t")
                for c in value
            ):
                raise ValueError(f"Invalid translation: {language}:{key}")
            if not value.strip() and english[key].strip():
                raise ValueError(f"Empty translation: {language}:{key}")
            if placeholders(value) != placeholders(english[key]):
                raise ValueError(f"Placeholder mismatch: {language}:{key}")
            if key.startswith("statusline.") and any(unicodedata.category(c) in ("Cc", "Cs", "Zl", "Zp") for c in value):
                raise ValueError(f"Statusline messages must be single-line terminal-safe text: {language}:{key}")
            if key.startswith(("statusline.prefix.", "statusline.short.", "statusline.values.", "statusline.live.label.")) and placeholders(value):
                raise ValueError(f"Statusline labels and enum values cannot contain placeholders: {language}:{key}")
    return data


def generated(data=None):
    data = resources() if data is None else data
    names = registry()
    return (
        "// Generated by tools/generation/resources.ts; do not edit.\n"
        + "export const LANGUAGES = " + json.dumps(list(names)) + " as const;\n"
        + "export type Language = typeof LANGUAGES[number];\n"
        + "export const LANGUAGE_NAMES: Record<Language, string> = " + json.dumps(names, ensure_ascii=False) + ";\n"
        + "export const LOCALES = " + json.dumps(data, ensure_ascii=False, indent=2)
        + " as const;\nexport type MessageKey = keyof typeof LOCALES.en;\n"
    )


def generated_files():
    data, names = resources(), registry()
    module_names = {code: code.replace("-", "_").lower() for code in names}
    files = {
        OUTPUT: generated(data),
        REGISTRY_OUTPUT: (
            HEADER + "LANGUAGES = tuple(" + json.dumps(list(names)) + ")\n"
            + "LANGUAGE_NAMES = " + json.dumps(names, ensure_ascii=False, indent=2) + "\n"
            + "STATUSLINE_MODULES = " + json.dumps(module_names, ensure_ascii=False, indent=2) + "\n"
        ),
        STATUSLINE_OUTPUT / "__init__.py": HEADER + '"""Language modules are imported individually on demand."""\n',
    }
    for code, entries in data.items():
        messages = {key: value for key, value in entries.items() if key.startswith("statusline.")}
        files[STATUSLINE_OUTPUT / (module_names[code] + ".py")] = (
            HEADER + "MESSAGES = " + json.dumps(messages, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        )
    return files


def coverage():
    data = resources(complete=False)
    keys = set(data["en"])
    return {
        language: {
            "messages": len(entries), "total": len(keys),
            "percent": round(100 * len(entries) / len(keys), 2),
            "missing": sorted(keys - set(entries)),
            "statusline_messages": sum(key.startswith("statusline.") for key in entries),
        }
        for language, entries in data.items()
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="validate resources and generated bytes without writing")
    mode.add_argument("--coverage", action="store_true", help="report key coverage as JSON without writing")
    args = parser.parse_args()
    if not args.check and not args.coverage:
        parser.error("Generation is owned by TypeScript; run npm run generate")
    if args.coverage:
        report = coverage()
        print(json.dumps(report, ensure_ascii=False, indent=2))
        return int(any(row["missing"] for row in report.values()))
    files = generated_files()
    obsolete = set(STATUSLINE_OUTPUT.glob("*.py")) - set(files)
    legacy = STATUSLINE_OUTPUT.with_suffix(".py")
    if legacy.exists():
        obsolete.add(legacy)
    if args.check:
        if obsolete or any(not path.is_file() or path.read_text(encoding="utf-8") != value for path, value in files.items()):
            parser.exit(1, "Generated locales are stale; run npm run generate\n")
    else:
        for path, value in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding="utf-8")
        for path in obsolete:
            path.unlink()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
