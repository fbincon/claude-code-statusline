"""Generate the independent runtime wire types from their Python definition."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import types
from typing import get_args, get_origin, get_type_hints, Literal

from claude_statusline.runtime.live import model


def type_name(value):
    if value in (str, int, float, type(None), dict):
        return {
            str: "string",
            int: "number",
            float: "number",
            type(None): "null",
            dict: "Record<string, unknown>",
        }[value]
    if get_origin(value) is Literal:
        return " | ".join(json.dumps(v) for v in get_args(value))
    if get_origin(value) is types.UnionType:
        return " | ".join(type_name(v) for v in get_args(value))
    raise ValueError(f"Unmapped runtime type: {value}")


def generated():
    rows = [
        "// Generated by tools/generate_runtime_contracts.py; do not edit.",
        f"export const PROTOCOL_VERSION = {model.PROTOCOL_VERSION} as const;",
        "export type Source = " + type_name(model.Source) + ";",
        "export type Kind = " + type_name(model.Kind) + ";",
        "export interface Observation {",
    ]
    rows.extend(
        f"  {key}: {type_name(value)};"
        for key, value in get_type_hints(model.Observation).items()
    )
    return "\n".join([*rows, "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path("mods/statusline-runtime/lib/generated-contracts.ts")
    content = generated()
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != content:
            parser.exit(
                1,
                "Runtime contracts are stale; run tools/generate_runtime_contracts.py\n",
            )
    else:
        target.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
