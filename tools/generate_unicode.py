"""Reproduce compact Unicode 18.0 tables; refresh requires wcwidth==0.9.1."""

from __future__ import annotations

import argparse
import hashlib
import importlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tools/unicode"
VERSION = "18.0.0"
REFERENCE = "0.9.1"
PROPERTIES = (
    "CR",
    "LF",
    "CONTROL",
    "EXTEND",
    "ZWJ",
    "REGIONAL_INDICATOR",
    "PREPEND",
    "SPACINGMARK",
    "L",
    "V",
    "T",
    "LV",
    "LVT",
)


def refresh():
    import wcwidth

    if wcwidth.__version__ != REFERENCE or wcwidth.list_versions() != (VERSION,):
        raise SystemExit("Refresh requires wcwidth==0.9.1 with Unicode 18.0.0")
    tables, sources = {}, {}
    for module, names in {
        "table_zero": ("ZERO_WIDTH",),
        "table_wide": ("WIDE_EASTASIAN",),
        "table_vs16": ("VS16_NARROW_TO_WIDE",),
        "table_vs15": ("VS15_WIDE_TO_NARROW",),
        "table_mc": ("CATEGORY_MC",),
        "table_grapheme": tuple("GRAPHEME_" + p for p in PROPERTIES)
        + (
            "EXTENDED_PICTOGRAPHIC",
            "INCB_LINKER",
            "INCB_CONSONANT",
            "INCB_EXTEND",
            "ISC_VIRAMA",
            "ISC_INVISIBLE_STACKER",
        ),
    }.items():
        source = importlib.import_module("wcwidth." + module)
        sources[module + ".py"] = hashlib.sha256(
            Path(source.__file__).read_bytes()
        ).hexdigest()
        for name in names:
            value = getattr(source, name)
            if isinstance(value, dict):
                value = value["9.0.0" if name.startswith("VS") else VERSION]
            tables[name] = value
    value = {
        "unicode_version": VERSION,
        "reference": "wcwidth " + REFERENCE,
        "source_url": "https://pypi.org/project/wcwidth/0.9.1/",
        "source_sha256": sources,
        "tables": tables,
    }
    (DATA / "data.json").write_text(
        json.dumps(value, separators=(",", ":")) + "\n", encoding="utf-8"
    )


def conformance():
    cases = []
    for line in (
        (DATA / "GraphemeBreakTest.txt").read_text(encoding="utf-8").splitlines()
    ):
        tokens = line.split("#")[0].split()
        if not tokens:
            continue
        groups, group = [], ""
        for token in tokens:
            if token == "÷":
                if group:
                    groups.append(group)
                    group = ""
            elif token != "×":
                group += chr(int(token, 16))
        cases.append(groups)
    return cases


def outputs():
    raw = (DATA / "data.json").read_bytes()
    source = json.loads(raw)
    assert (
        source["unicode_version"] == VERSION
        and source["reference"] == "wcwidth " + REFERENCE
    )
    tables = source["tables"]
    width = {
        name: tables[name]
        for name in (
            "ZERO_WIDTH",
            "WIDE_EASTASIAN",
            "VS16_NARROW_TO_WIDE",
            "VS15_WIDE_TO_NARROW",
            "CATEGORY_MC",
            "EXTENDED_PICTOGRAPHIC",
        )
    }
    width["VIRAMA"] = sorted(tables["ISC_VIRAMA"] + tables["ISC_INVISIBLE_STACKER"])
    grapheme = {
        name: tables[name]
        for name in (
            "EXTENDED_PICTOGRAPHIC",
            "INCB_LINKER",
            "INCB_CONSONANT",
            "INCB_EXTEND",
        )
    }
    grapheme["BREAK_PROPERTIES"] = sorted(
        [lo, hi, number]
        for number, name in enumerate(PROPERTIES, 1)
        for lo, hi in tables["GRAPHEME_" + name]
        if name not in ("LV", "LVT")
    )
    license_text = (
        (DATA / "WCWIDTH-LICENSE.txt").read_text(encoding="utf-8")
        + "\n"
        + (DATA / "UNICODE-LICENSE.txt").read_text(encoding="utf-8")
    )
    digest = hashlib.sha256(raw).hexdigest()
    header = f"Generated by tools/generate_unicode.py; Unicode {VERSION}; wcwidth {REFERENCE}; data SHA256 {digest}."

    def python(values):
        return (
            '"""'
            + header
            + "\n\n"
            + license_text.replace('"""', "")
            + '"""\n\n'
            + "\n".join(
                name
                + " = (\n"
                + "".join("    " + repr(tuple(row)) + ",\n" for row in rows)
                + ")\n"
                for name, rows in values.items()
            )
        )

    yield ROOT / "src/claude_statusline/rendering/_unicode_width.py", python(width)
    yield (
        ROOT / "src/claude_statusline/rendering/_unicode_grapheme.py",
        python(grapheme),
    )
    yield (
        ROOT / "mods/statusline-native/lib/generated-unicode.ts",
        (
            "/* "
            + header
            + "\n"
            + license_text.replace("*/", "* /")
            + "*/\n"
            + "\n".join(
                "export const "
                + name
                + ": readonly (readonly ["
                + ", ".join(["number"] * len(rows[0]))
                + "])[] = "
                + json.dumps(rows, separators=(",", ":"))
                + ";"
                for name, rows in {**width, **grapheme}.items()
            )
            + "\n"
        ),
    )
    cases = json.loads(
        (ROOT / "tests/fixtures/graphemes.json").read_text(encoding="utf-8")
    )
    yield (
        ROOT / "mods/statusline-native/tests/generated-unicode-fixtures.ts",
        (
            "// Generated by tools/generate_unicode.py; do not edit.\n"
            + "export const GRAPHEME_CASES = "
            + json.dumps(cases["cases"], ensure_ascii=True)
            + ";\n"
            + "export const BREAK_CASES = "
            + json.dumps(conformance(), ensure_ascii=True)
            + ";\n"
        ),
    )
    yield (
        DATA / "provenance.json",
        json.dumps(
            {
                "unicode_version": VERSION,
                "reference": "wcwidth " + REFERENCE,
                "data_sha256": digest,
                "source_sha256": source["source_sha256"],
                "conformance_url": "https://www.unicode.org/Public/18.0.0/ucd/auxiliary/GraphemeBreakTest.txt",
                "conformance_sha256": hashlib.sha256(
                    (DATA / "GraphemeBreakTest.txt").read_bytes()
                ).hexdigest(),
                "conformance_cases": len(conformance()),
                "licenses": ["WCWIDTH-LICENSE.txt", "UNICODE-LICENSE.txt"],
            },
            indent=2,
        )
        + "\n",
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.refresh and args.check:
        parser.error("--refresh and --check are mutually exclusive")
    if args.refresh:
        refresh()
    for path, content in outputs():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale Unicode resource: {path.relative_to(ROOT)}")
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
